# Helper conversion functions
def _kelvin_to_celsius(k: float) -> float:
    return round(k - 273.15, 2)


def _flux_to_mm_per_day(flux: float) -> float:
    # 1 kg/m^2/s = 1 mm/s = 86400 mm/day of liquid water
    return round(flux * 86400.0, 3)


def _identity(v: float) -> float:
    return round(v, 4)


def _round3(v: float) -> float:
    return round(v, 3)


